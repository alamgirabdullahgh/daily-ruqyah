# চোখ-গুচ্ছে শব্দটি থাকলেও যেসব রুটে অর্থ শরীরের চোখ নয় (আড়াল/অদৃশ্য/ফিরিয়ে দেওয়া/চোখ বুজে থাকা-র বাগধারা) সেগুলো বাদ
GLOSS_EXCL_ROOTS = {"حجب", "صرف", "غيب", "غمض"}

BN_SUF = ["", "ে", "কে", "র", "ের", "েরকে", "গুলো", "গুলোকে", "গুলোর", "গুলোতে", "সমূহ", "দের", "য়", "য়ে", "য়ের"]


def norm(s):
    s = s.replace("‌", "").replace("‍", "").replace("ঁ", "")
    return re.sub(r"[()\[\],.;:!?\"'“”‘’।–—-]", "", s)


def gloss_hit(gloss, words):
    toks = [norm(t) for t in re.split(r"\s+", gloss) if norm(t)]
    for t in toks:
        for w in words:
            if any(t == w + sf for sf in BN_SUF):
                return True
    return False


def main():
    cand = json.load(open(D / "ayah-candidates.json"))["cells"]
    roots = {r: forms for r, forms in json.load(open(D / "quran-roots.json"))["roots"]}
    ayn = {}

    def n_ayat(s):
        if s not in ayn:
            ayn[s] = len(json.load(open(D / "quran-chunks" / "a" / f"{s}.json")))
        return ayn[s]

    def word_refs(spec):
        kind, v = spec
        out = {}
        for r, forms in roots.items():
            for f in forms:
                form, lemma, refs, gloss = f[0], f[1], f[2], f[3] if len(f) > 3 else ""
                if kind == "root":
                    if r != v:
                        continue
                elif r in GLOSS_EXCL_ROOTS or not gloss_hit(gloss, v):
                    continue
                for ref in refs.split(","):
                    p = ref.split(":")
                    if len(p) >= 3:
                        out.setdefault((int(p[0]), int(p[1])), int(p[2]))
        return out

    cells, miss = {}, []
    for key, lst in cand.items():
        direct = [x for x in lst if x["kind"] == "direct"]
        base = (direct or lst)[0]
        s, a = base["s"], base["a"]
        if key in CELL_PORT:
            cs, ca, f, t = CELL_PORT[key]
            assert (cs, ca) == (s, a), f"{key}: CELL_PORT আয়াত মেলে না ({cs}:{ca} ≠ {s}:{a})"
        elif (s, a) in PORT:
            f, t = PORT[(s, a)]
        else:
            miss.append(key)
            continue
        nw = len(json.load(open(D / "quran-chunks" / "a" / f"{s}.json"))[a - 1].split(" "))
        assert 1 <= f <= t <= nw, f"{key}: {s}:{a} অংশ [{f},{t}] সীমার বাইরে (শব্দ {nw})"
        more, seen = {}, {(s, a)}
        for x in lst:
            k = (x["s"], x["a"])
            if k not in seen:
                seen.add(k)
                more[k] = 0
        if key in WORDS:
            for k, w in word_refs(WORDS[key]).items():
                if k not in seen:
                    seen.add(k)
                    more[k] = w
        ms = [f"{k[0]}:{k[1]}" + (f":{w}" if w else "") for k, w in sorted(more.items())]
        cells[key] = {"b": [[s, a, f, t]], "m": ms}
    if miss:
        sys.exit("PORT-এ নেই: " + ", ".join(miss))

    out = {
        "_doc": "সাত-অক্ষের চার্টের আয়াত। ঘরের চাবি গ্রুপ.অক্ষ.অপশন। b = মৌলিক আয়াত [সূরা, আয়াত, শুরু-শব্দ, শেষ-শব্দ] (আরবি শব্দ-নম্বর ১ থেকে; এই অংশ মার্ক হয়); m = বাকি আয়াত (\"সূরা:আয়াত\" বা \"সূরা:আয়াত:শব্দ\")। tools/build-axis-ayat.py দিয়ে তৈরি — হাতে বদলাবেন না, স্ক্রিপ্ট বদলে আবার চালান।",
        "v": 1,
        "axes": [{"name": n, "slug": sl, "cols": [{"name": COLS[i], "opts": o} for i, o in enumerate(cols)]} for n, sl, cols in GROUPS],
        "cells": cells,
    }
    (D / "axis-ayat.json").write_text(json.dumps(out, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    tot = sum(len(c["m"]) for c in cells.values())
    print(f"ঘর {len(cells)}টি; বাকি আয়াত মোট {tot}টি")
    for k, c in cells.items():
        if len(c["m"]) > 8:
            print(" ", k, "→", len(c["m"]), "আয়াত")


if __name__ == "__main__":
    main()
